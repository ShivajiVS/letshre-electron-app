"use strict";

/**
 * Generates a pseudo-localization bundle: every leaf string in en.json, padded
 * ~35% longer and with Latin letters swapped for accented lookalikes. Padding
 * exercises layout overflow the way a longer real translation would; the
 * accents make any text that DIDN'T get pseudo-localized (a hardcoded string
 * that bypassed tr()/t()) visually obvious against the accented text around it.
 *
 * WHY this writes to assets/locales-dev/ instead of assets/locales/, and does
 * NOT touch SUPPORTED_LOCALES: assets/locales/ is the certified, production-
 * shipped set gated by each locale's `reviewed` flag (src/shared/constants.js);
 * wiring a synthetic QA locale into that same mechanism would add a permanent
 * third code path nobody asked for. This is a dev-only artifact — load it
 * manually:
 *
 *   1. node scripts/generate-pseudo-locale.js
 *   2. Copy assets/locales-dev/qps-ploc.json to assets/locales/qps-ploc.json
 *   3. Temporarily add to SUPPORTED_LOCALES in src/shared/constants.js:
 *        { code: "qps-ploc", name: "Pseudo (QA)", dir: "ltr", reviewed: true }
 *   4. Run the app, switch to it via the language switcher, look for
 *      un-accented (i.e. untranslated) text and layout overflow/clipping.
 *   5. Revert steps 2-3 before committing — this locale must never ship.
 *
 * Walks en.json's nested structure the same way test/locales.test.js and
 * scripts/sync-locale-provenance.js's flatten() do: skip any key starting
 * with "_" (metadata, not translatable content).
 *
 * Usage: node scripts/generate-pseudo-locale.js
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const EN_PATH = path.join(ROOT, "assets/locales/en.json");
const OUT_DIR = path.join(ROOT, "assets/locales-dev");
const OUT_PATH = path.join(OUT_DIR, "qps-ploc.json");

const ACCENT_MAP = {
  a: "á",
  b: "ƀ",
  c: "ç",
  d: "đ",
  e: "é",
  f: "ƒ",
  g: "ĝ",
  h: "ĥ",
  i: "í",
  j: "ĵ",
  k: "ķ",
  l: "ĺ",
  m: "ɱ",
  n: "ñ",
  o: "ó",
  p: "ρ",
  q: "ʠ",
  r: "ŕ",
  s: "š",
  t: "ţ",
  u: "ú",
  v: "ν",
  w: "ŵ",
  x: "ẋ",
  y: "ý",
  z: "ž",
};

function accentify(text) {
  return [...text]
    .map((ch) => {
      const mapped = ACCENT_MAP[ch.toLowerCase()];
      if (!mapped) {
        return ch;
      }
      return ch === ch.toLowerCase() ? mapped : mapped.toUpperCase();
    })
    .join("");
}

/**
 * Splits a string into text segments and opaque `{...}` spans (balanced-brace
 * scan, so nested plural blocks like `{n, plural, one {# thing} other
 * {# things}}` come out as a single span rather than being cut mid-structure).
 * Text segments get pseudo-localized; token/plural spans pass through verbatim.
 */
function splitPreservingBraces(str) {
  const segments = [];
  let i = 0;
  let textStart = 0;
  while (i < str.length) {
    if (str[i] === "{") {
      if (i > textStart) {
        segments.push({ type: "text", value: str.slice(textStart, i) });
      }
      let depth = 1;
      let j = i + 1;
      while (j < str.length && depth > 0) {
        if (str[j] === "{") {
          depth++;
        } else if (str[j] === "}") {
          depth--;
        }
        j++;
      }
      segments.push({ type: "token", value: str.slice(i, j) });
      i = j;
      textStart = j;
    } else {
      i++;
    }
  }
  if (textStart < str.length) {
    segments.push({ type: "text", value: str.slice(textStart) });
  }
  return segments;
}

function pseudoizeString(value) {
  const segments = splitPreservingBraces(value);
  const transformed = segments
    .map((seg) => (seg.type === "text" ? accentify(seg.value) : seg.value))
    .join("");
  const extra = Math.max(2, Math.round(value.length * 0.35));
  const filler = "‧".repeat(extra);
  return `[${transformed}${filler}]`;
}

function transform(node) {
  if (typeof node === "string") {
    return pseudoizeString(node);
  }
  if (Array.isArray(node)) {
    return node.map(transform);
  }
  if (node && typeof node === "object") {
    const out = {};
    for (const [key, value] of Object.entries(node)) {
      out[key] = key.startsWith("_") ? value : transform(value);
    }
    return out;
  }
  return node;
}

function main() {
  const en = JSON.parse(fs.readFileSync(EN_PATH, "utf8"));
  const pseudo = transform(en);
  pseudo._meta = {
    locale: "qps-ploc",
    name: "Pseudo (QA)",
    dir: "ltr",
    note: "Auto-generated by scripts/generate-pseudo-locale.js for manual QA only. Never ship.",
  };
  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(OUT_PATH, `${JSON.stringify(pseudo, null, 2)}\n`, "utf8");
  // eslint-disable-next-line no-console
  console.log(`wrote ${path.relative(ROOT, OUT_PATH)}`);
}

if (require.main === module) {
  main();
}

module.exports = { pseudoizeString, transform, accentify, splitPreservingBraces };
